export function getValidChaos(nodeType: string): string[] {
  return (
    VALID_CHAOS[nodeType] ??
    VALID_CHAOS[nodeType?.toLowerCase()] ??
    VALID_CHAOS['microservice'] ??
    []
  );
}

export function isChaosValid(chaosType: string, nodeType: string): boolean {
  return getValidChaos(nodeType).includes(chaosType);
}

